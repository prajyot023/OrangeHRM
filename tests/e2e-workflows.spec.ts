import { test, expect } from '../fixtures/pageFixtures';
import { Credentials } from '../utils/testData';

/**
 * End-to-End Workflow Tests
 * Complete user journey tests spanning multiple modules
 */

test.describe('E2E Workflow Tests', () => {

  test('TC-E2E-001: Complete Login → Dashboard → PIM → Logout Flow', async ({
    loginPage,
    dashboardPage,
    pimPage,
    page,
  }) => {
    // Step 1: Login
    await loginPage.goto();
    await loginPage.loginAsAdmin(
      Credentials.ADMIN.username,
      Credentials.ADMIN.password
    );

    // Step 2: Verify Dashboard
    await dashboardPage.expectDashboardLoaded();
    const title = await dashboardPage.getDashboardTitle();
    expect(title.trim()).toBe('Dashboard');

    // Step 3: Navigate to PIM
    await dashboardPage.clickSidebarMenu('PIM');
    await pimPage.expectPIMPageLoaded();

    // Step 4: Verify employee records exist
    const recordCount = await pimPage.getRecordCount();
    expect(recordCount).toBeGreaterThan(0);

    // Step 5: Logout
    await pimPage.logout();
    await expect(page).toHaveURL(/.*auth\/login/);
  });

  test('TC-E2E-002: Complete Login → Navigate All Modules → Logout', async ({
    loginPage,
    dashboardPage,
    page,
  }) => {
    // Login
    await loginPage.goto();
    await loginPage.loginAsAdmin(
      Credentials.ADMIN.username,
      Credentials.ADMIN.password
    );

    // Navigate through each module
    const modules = ['Admin', 'PIM', 'Leave', 'Directory', 'My Info', 'Buzz'];

    for (const module of modules) {
      await dashboardPage.clickSidebarMenu(module);
      // Wait for page to load
      await dashboardPage.waitForPageLoad();
    }

    // Navigate back to Dashboard
    await dashboardPage.clickSidebarMenu('Dashboard');
    await expect(page).toHaveURL(/.*dashboard\/index/);

    // Logout
    await dashboardPage.logout();
    await expect(page).toHaveURL(/.*auth\/login/);
  });

  test('TC-E2E-003: Login → PIM Add Employee → Verify → Logout', async ({
    loginPage,
    dashboardPage,
    pimPage,
    page,
  }) => {
    // Login
    await loginPage.goto();
    await loginPage.loginAsAdmin(
      Credentials.ADMIN.username,
      Credentials.ADMIN.password
    );

    // Navigate to PIM Add Employee
    await dashboardPage.clickSidebarMenu('PIM');
    await pimPage.expectPIMPageLoaded();
    await pimPage.clickAddEmployee();
    await pimPage.expectAddEmployeeFormLoaded();

    // Verify auto-generated employee ID
    const empId = await pimPage.getAutoGeneratedEmployeeId();
    expect(empId.length).toBeGreaterThan(0);

    // Add employee
    const uniqueSuffix = Date.now().toString().slice(-5);
    await pimPage.addEmployee('E2E', 'Test', `User${uniqueSuffix}`);

    // Verify redirect to personal details
    await expect(page).toHaveURL(/.*pim\/viewPersonalDetails/, { timeout: 15000 });

    // Logout
    await pimPage.logout();
    await expect(page).toHaveURL(/.*auth\/login/);
  });

  test('TC-E2E-004: Login → My Info → Update & Navigate Tabs → Logout', async ({
    loginPage,
    myInfoPage,
    page,
  }) => {
    // Login
    await loginPage.goto();
    await loginPage.loginAsAdmin(
      Credentials.ADMIN.username,
      Credentials.ADMIN.password
    );

    // Navigate to My Info
    await myInfoPage.goto();
    await myInfoPage.expectMyInfoPageLoaded();

    // Verify form is populated
    const firstName = await myInfoPage.getFirstName();
    expect(firstName.length).toBeGreaterThan(0);

    // Navigate through tabs
    await myInfoPage.switchToTab('Contact Details');
    await expect(myInfoPage.street1Input).toBeVisible();

    await myInfoPage.switchToTab('Emergency Contacts');
    await myInfoPage.switchToTab('Dependents');

    // Return to Personal Details
    await myInfoPage.switchToTab('Personal Details');
    await expect(myInfoPage.firstNameInput).toBeVisible();

    // Logout
    await myInfoPage.logout();
    await expect(page).toHaveURL(/.*auth\/login/);
  });

  test('TC-E2E-005: Login → Admin Search → Directory Search → Leave List → Logout', async ({
    loginPage,
    adminPage,
    directoryPage,
    leavePage,
    page,
  }) => {
    // Login
    await loginPage.goto();
    await loginPage.loginAsAdmin(
      Credentials.ADMIN.username,
      Credentials.ADMIN.password
    );

    // Admin - Search by username
    await adminPage.goto();
    await adminPage.expectAdminPageLoaded();
    await adminPage.searchByUsername('Admin');
    const adminCount = await adminPage.getRecordCount();
    expect(adminCount).toBeGreaterThanOrEqual(1);

    // Directory - View directory
    await directoryPage.goto();
    await directoryPage.expectDirectoryPageLoaded();
    const dirCount = await directoryPage.getRecordCount();
    expect(dirCount).toBeGreaterThan(0);

    // Leave - View leave list
    await leavePage.goto();
    await leavePage.expectLeaveListLoaded();

    // Logout
    await leavePage.logout();
    await expect(page).toHaveURL(/.*auth\/login/);
  });

  test('TC-E2E-006: Verify session persistence across page navigation', async ({
    loginPage,
    dashboardPage,
    page,
  }) => {
    // Login
    await loginPage.goto();
    await loginPage.loginAsAdmin(
      Credentials.ADMIN.username,
      Credentials.ADMIN.password
    );

    // Navigate to multiple pages
    await dashboardPage.clickSidebarMenu('Admin');
    await dashboardPage.waitForPageLoad();

    await dashboardPage.clickSidebarMenu('PIM');
    await dashboardPage.waitForPageLoad();

    await dashboardPage.clickSidebarMenu('Leave');
    await dashboardPage.waitForPageLoad();

    await dashboardPage.clickSidebarMenu('Dashboard');
    await dashboardPage.waitForPageLoad();

    // Verify user is still logged in (user dropdown is visible)
    await expect(dashboardPage.userDropdown).toBeVisible();

    // Verify user name is still displayed
    const userName = await dashboardPage.getLoggedInUserName();
    expect(userName.trim().length).toBeGreaterThan(0);
  });
});
