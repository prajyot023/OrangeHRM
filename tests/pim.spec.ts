import { test, expect } from '../fixtures/pageFixtures';
import { Credentials, EmployeeData } from '../utils/testData';
import { generateUniqueId } from '../utils/helpers';

/**
 * PIM Module - End-to-End Tests
 * Tests for employee management: add, search, edit, delete employees
 */

test.describe('PIM Module Tests', () => {
  test.beforeEach(async ({ loginPage }) => {
    await loginPage.goto();
    await loginPage.loginAsAdmin(
      Credentials.ADMIN.username,
      Credentials.ADMIN.password
    );
  });

  test('TC-PIM-001: Verify PIM Employee List page loads', async ({ pimPage }) => {
    await pimPage.goto();
    await pimPage.expectPIMPageLoaded();
  });

  test('TC-PIM-002: Verify employee table is displayed with records', async ({ pimPage }) => {
    await pimPage.goto();
    await pimPage.expectPIMPageLoaded();

    const recordCount = await pimPage.getRecordCount();
    expect(recordCount).toBeGreaterThan(0);
  });

  test('TC-PIM-003: Navigate to Add Employee page', async ({ pimPage }) => {
    await pimPage.goto();
    await pimPage.clickAddEmployee();
    await pimPage.expectAddEmployeeFormLoaded();
  });

  test('TC-PIM-004: Add a new employee with basic details', async ({ pimPage, page }) => {
    const uniqueId = generateUniqueId();

    await pimPage.gotoAddEmployee();
    await pimPage.expectAddEmployeeFormLoaded();

    await pimPage.addEmployee(
      EmployeeData.NEW_EMPLOYEE.firstName,
      EmployeeData.NEW_EMPLOYEE.middleName,
      `${EmployeeData.NEW_EMPLOYEE.lastName}_${uniqueId}`
    );

    // Verify redirect to personal details page (employee was created)
    await expect(page).toHaveURL(/.*pim\/viewPersonalDetails/, { timeout: 15000 });
  });

  test('TC-PIM-005: Verify auto-generated Employee ID on Add form', async ({ pimPage }) => {
    await pimPage.gotoAddEmployee();
    await pimPage.expectAddEmployeeFormLoaded();

    const employeeId = await pimPage.getAutoGeneratedEmployeeId();
    expect(employeeId.length).toBeGreaterThan(0);
  });

  test('TC-PIM-006: Search employee by Employee ID', async ({ pimPage }) => {
    await pimPage.goto();
    await pimPage.expectPIMPageLoaded();

    // Search with a known ID (0100 is a common demo ID)
    await pimPage.searchByEmployeeId('0100');

    // Should show results or no records - verify table is still visible
    await expect(pimPage.employeeTable).toBeVisible();
  });

  test('TC-PIM-007: Reset search filters', async ({ pimPage }) => {
    await pimPage.goto();
    await pimPage.expectPIMPageLoaded();

    // Enter a search term
    await pimPage.employeeIdInput.fill('9999');
    await pimPage.searchButton.click();
    await pimPage.waitForPageLoad();

    // Reset and verify filters are cleared
    await pimPage.resetSearch();
    const idValue = await pimPage.employeeIdInput.inputValue();
    expect(idValue).toBe('');
  });

  test('TC-PIM-008: Verify table headers on PIM list', async ({ pimPage }) => {
    await pimPage.goto();
    await pimPage.expectPIMPageLoaded();

    const headers = pimPage.tableHeaders;
    const headerCount = await headers.count();
    expect(headerCount).toBeGreaterThanOrEqual(5);
  });

  test('TC-PIM-009: Edit first employee record', async ({ pimPage, page }) => {
    await pimPage.goto();
    await pimPage.expectPIMPageLoaded();

    const recordCount = await pimPage.getRecordCount();
    if (recordCount > 0) {
      await pimPage.editFirstEmployee();
      // Verify navigated to personal details edit page
      await expect(page).toHaveURL(/.*pim\/viewPersonalDetails/);
    }
  });

  test('TC-PIM-010: Verify Add Employee page has all required fields', async ({ pimPage }) => {
    await pimPage.gotoAddEmployee();

    // Verify all form fields are present
    await expect(pimPage.firstNameInput).toBeVisible();
    await expect(pimPage.middleNameInput).toBeVisible();
    await expect(pimPage.lastNameInput).toBeVisible();
    await expect(pimPage.employeeIdField).toBeVisible();
    await expect(pimPage.saveButton).toBeVisible();
  });

  test('TC-PIM-011: Search employee by name using autocomplete', async ({ pimPage }) => {
    await pimPage.goto();
    await pimPage.expectPIMPageLoaded();

    // Type partial employee name to trigger autocomplete
    const nameInput = pimPage.page.locator(
      '.oxd-input-group:has(.oxd-label:text("Employee Name")) input'
    ).first();
    await nameInput.fill('Paul');
    await pimPage.page.waitForTimeout(1500);

    // Check if autocomplete suggestions appear
    const autocomplete = pimPage.page.locator('.oxd-autocomplete-option');
    const count = await autocomplete.count();
    // If autocomplete shows results, click the first one
    if (count > 0) {
      await autocomplete.first().click();
    }

    await pimPage.searchButton.click();
    await pimPage.waitForPageLoad();

    // Verify table is displayed with search results
    await expect(pimPage.employeeTable).toBeVisible();
  });
});
